"""Rewrite the curated "USDA" foods in src/lol/core/foods.py with real FoodData Central values.

    python -I tools/foods/sync_curated.py [--asset src/assets/data/usda_foods.json.gz] [--dry]

For every id in curated_fdc.CURATED_FDC: finds that exact FDC description in the built asset,
replaces kcal/protein/carbs/fat in its `_u("id", ...)` line and writes the fdc ids to
src/lol/core/foods_fdc.py. Prints each change, flagging kcal changes over 10 %.
"""

from __future__ import annotations

import argparse
import gzip
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

from curated_fdc import CURATED_FDC

FOODS_PY = ROOT / "src/lol/core/foods.py"
FDC_PY = ROOT / "src/lol/core/foods_fdc.py"
NUM = r"-?\d+(?:\.\d+)?"


def fmt(v: float) -> str:
    v = round(float(v), 1)
    return str(int(v)) if v.is_integer() else str(v)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--asset", type=Path, default=ROOT / "src/assets/data/usda_foods.json.gz")
    ap.add_argument("--dry", action="store_true")
    a = ap.parse_args()
    with gzip.open(a.asset, "rt", encoding="utf-8") as fh:
        doc = json.load(fh)
    by_name = {r[1].lower(): r for r in doc["foods"]}
    src = FOODS_PY.read_text(encoding="utf-8")
    ids: dict[str, int] = {}
    big = changed = 0
    for fid, desc in CURATED_FDC.items():
        row = by_name.get(desc.lower())
        if row is None:
            print(f"!! {fid}: not in asset: {desc}")
            continue
        fdc, _name, _cat, kcal, p, c, f = row[:7]
        ids[fid] = int(fdc)
        pat = re.compile(rf'(_u\("{re.escape(fid)}", "[^"]*", )({NUM}), ({NUM}), ({NUM}), '
                         rf'({NUM})(,)')
        m = pat.search(src)
        if not m:
            print(f"!! {fid}: _u line not found in foods.py")
            continue
        old = [float(x) for x in m.group(2, 3, 4, 5)]
        new = [float(kcal), float(p), float(c), float(f)]
        if [round(x, 1) for x in old] != [round(x, 1) for x in new]:
            changed += 1
            pct = (new[0] - old[0]) / old[0] * 100 if old[0] else 0.0
            flag = " >10%" if abs(pct) > 10 else ""
            big += bool(flag)
            print(f"{fid:16} kcal {fmt(old[0])}->{fmt(new[0])} ({pct:+.0f}%) "
                  f"P {fmt(old[1])}->{fmt(new[1])} C {fmt(old[2])}->{fmt(new[2])} "
                  f"F {fmt(old[3])}->{fmt(new[3])}  [fdc {fdc}]{flag}")
            src = src[:m.start()] + m.group(1) + ", ".join(fmt(x) for x in new) + "," + \
                src[m.end():]
    print(f"{len(ids)} matched, {changed} changed, {big} with kcal change > 10%")
    if a.dry:
        return
    FOODS_PY.write_text(src, encoding="utf-8")
    lines = ['"""GENERATED by tools/foods/sync_curated.py - FoodData Central ids of the curated',
             'USDA foods in foods.py (values there were synced from these entries)."""', "",
             "FDC_IDS: dict[str, int] = {"]
    lines += [f'    "{k}": {v},' for k, v in sorted(ids.items())]
    lines.append("}")
    FDC_PY.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
