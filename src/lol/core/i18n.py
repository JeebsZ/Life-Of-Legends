def tr(text: str, lang: str | None = None) -> str:
    """Translate `text` into `lang` (or the active language), falling back to `text`."""
    code = lang if lang is not None else _CURRENT_LANG
    if code == "en" or code not in TRANSLATIONS:
        return text
    return TRANSLATIONS[code].get(text, text)


